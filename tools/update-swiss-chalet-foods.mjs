import { mkdir, writeFile } from "node:fs/promises";

const SOURCE_URL = "https://www.swisschalet.com/en/nutritional.html";
const SOURCE_NAME = "Swiss Chalet Canada";
const VERIFIED_AT = "2026-08-29";
const ROOT = new URL("../", import.meta.url);

const response = await fetch(SOURCE_URL, { headers: { "User-Agent": "Level-Up-Food-Catalogue/1.0" } });
if (!response.ok) throw new Error(`Swiss Chalet nutrition page returned ${response.status}`);
const html = await response.text();
const scripts = [...html.matchAll(/<script[^>]*type=["']application\/ld\+json["'][^>]*>([\s\S]*?)<\/script>/gi)];
const list = scripts
    .map(match => JSON.parse(match[1]))
    .find(value => value?.["@type"] === "ItemList" && Array.isArray(value.itemListElement));
if (!list) throw new Error("The official page did not contain its structured nutrition list.");

const toNumber = value => Number.parseFloat(String(value ?? "").replace(/[^\d.-]/g, ""));
const slug = value => String(value).normalize("NFKD").replace(/[^\w\s-]/g, "").trim().toLowerCase().replace(/[\s_]+/g, "-").replace(/-+/g, "-");
const sql = value => `'${String(value).replaceAll("'", "''")}'`;
const seenRows = new Set();
const idCounts = new Map();
const foods = [];

for (const item of list.itemListElement) {
    const grams = toNumber(item.servingSize);
    const row = {
        name: String(item.name || "").trim(),
        grams,
        calories: toNumber(item.calories),
        protein: toNumber(item.proteinContent),
        carbs: toNumber(item.carbohydrateContent),
        fat: toNumber(item.fatContent),
        fiber: toNumber(item.fiberContent) || 0
    };
    if (!row.name || !Number.isFinite(grams) || !Number.isFinite(row.calories)) continue;
    const signature = JSON.stringify(row);
    if (seenRows.has(signature)) continue;
    seenRows.add(signature);
    const baseId = `swiss-chalet-ca-${slug(row.name)}`;
    const occurrence = (idCounts.get(baseId) || 0) + 1;
    idCounts.set(baseId, occurrence);
    row.id = occurrence === 1 ? baseId : `${baseId}-${occurrence}`;
    foods.push(row);
}

if (foods.length < 200) throw new Error(`Expected at least 200 official foods; found ${foods.length}.`);
const fiesta = foods.find(food => food.name === "Fiesta Salad - Rotisserie Chicken");
if (!fiesta || fiesta.grams !== 728 || fiesta.calories !== 1090 || fiesta.protein !== 79 || fiesta.carbs !== 42 || fiesta.fat !== 70) {
    throw new Error("The Fiesta Salad validation record changed; review the official source before importing.");
}

const js = `// Generated by tools/update-swiss-chalet-foods.mjs from ${SOURCE_URL}\n` +
`// Verified ${VERIFIED_AT}. Do not edit by hand.\n` +
`export const SWISS_CHALET_FOODS = ${JSON.stringify(foods, null, 4)};\n`;

const values = foods.map(food => {
    const searchText = `${food.name} Swiss Chalet swisschalet restaurant Canada`.toLowerCase();
    return `  (${[
        sql(food.id), sql(food.name), sql("Swiss Chalet"), sql("Restaurant food"), sql("CA"), sql(searchText), "NULL",
        sql(`1 serving (${food.grams} g)`), food.grams, food.calories, food.protein, food.carbs, food.fat, food.fiber,
        sql(SOURCE_NAME), sql(SOURCE_URL), sql(VERIFIED_AT), sql("active"), sql(`${VERIFIED_AT}T00:00:00Z`), sql(`${VERIFIED_AT}T00:00:00Z`)
    ].join(", ")})`;
}).join(",\n");

const migration = `-- Generated from Swiss Chalet Canada's official structured nutrition catalogue.\n` +
`-- Source: ${SOURCE_URL} (verified ${VERIFIED_AT})\n` +
`INSERT OR REPLACE INTO verified_foods (\n` +
`  id, name, brand, category, country_code, search_text, barcode,\n` +
`  serving_label, serving_grams, calories, protein_g, carbs_g, fat_g, fiber_g,\n` +
`  source_name, source_url, verified_at, status, created_at, updated_at\n` +
`) VALUES\n${values};\n`;

await mkdir(new URL("cloud/src/data/", ROOT), { recursive: true });
await writeFile(new URL("cloud/src/data/swiss-chalet-foods.js", ROOT), js);
await writeFile(new URL("cloud/migrations/0009_swiss_chalet_foods.sql", ROOT), migration);
console.log(`Wrote ${foods.length} unique Swiss Chalet nutrition records.`);
