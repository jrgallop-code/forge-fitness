const CUSTOM_EXERCISE_STORAGE_KEY =
    "forge_custom_exercises";


export function getCustomExercises() {

    const stored =
        localStorage.getItem(
            CUSTOM_EXERCISE_STORAGE_KEY
        );


    if (!stored) {
        return [];
    }


    try {

        const customExercises =
            JSON.parse(
                stored
            );


        return Array.isArray(
            customExercises
        )
            ? customExercises
            : [];

    }

    catch {

        return [];

    }

}


export function getAllExercises() {

    return [
        ...exercises,
        ...getCustomExercises()
    ];

}


export function getExerciseById(id) {

    return getAllExercises()
        .find(
            exercise =>
                exercise.id === id
        );

}


export function addCustomExercise({
    name,
    muscleGroup,
    equipment,
    type,
    recommendedReps,
    defaultSets
}) {

    const cleanName =
        String(name || "")
            .trim();


    if (!cleanName) {
        return null;
    }


    const customExercises =
        getCustomExercises();


    const exercise = {

        id:
            `custom-${slugify(cleanName)}-${Date.now()}`,

        name:
            cleanName,

        muscleGroup:
            String(
                muscleGroup ||
                "Other"
            ),

        type:
            String(
                type ||
                "compound"
            ),

        equipment:
            String(
                equipment ||
                "Other"
            ),

        recommendedReps:
            String(
                recommendedReps ||
                "8-12"
            ),

        defaultSets:
            Math.max(
                1,
                Number(
                    defaultSets
                ) ||
                3
            ),

        trackingType:
            "reps",

        isCustom:
            true

    };


    customExercises.push(
        exercise
    );


    localStorage.setItem(
        CUSTOM_EXERCISE_STORAGE_KEY,
        JSON.stringify(
            customExercises
        )
    );


    return exercise;

}


function slugify(value) {

    return String(value)
        .toLowerCase()
        .replace(
            /[^a-z0-9]+/g,
            "-"
        )
        .replace(
            /^-|-$/g,
            ""
        ) ||
        "exercise";

}
